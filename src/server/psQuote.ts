/**
 * Κείμενο ως σταθερά PowerShell σε απλά εισαγωγικά. Για το PowerShell και τα τυπογραφικά ‘ ’ ‚ ‛ είναι απλά
 * εισαγωγικά: χωρίς διπλασιασμό, ένα όνομα σαν «O’Brien» κλείνει τη σταθερά και το υπόλοιπο εκτελείται.
 */
export const psQuote = (s: string): string => `'${s.replace(/['‘’‚‛]/g, '$&$&')}'`;
